// ─────────────────────────────────────────────────────────────────────────────
// Stream & Format DTOs
// ─────────────────────────────────────────────────────────────────────────────

export interface StreamFormatDto {
  formatId: string;
  quality: string;
  format: string;
  size: string;
  rawSize?: number;
  streamType: 'full' | 'mute' | 'audio' | 'stream' | 'muxed';
  hasAudio?: boolean;
  hasVideo?: boolean;
  fps?: string;
  bitrate?: string;
  url?: string;
  /** Codec video (ví dụ: av01, vp9, h264) */
  vcodec?: string;
  /** Codec audio (ví dụ: opus, aac, mp3) */
  acodec?: string;
}


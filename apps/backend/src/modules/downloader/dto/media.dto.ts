// ─────────────────────────────────────────────────────────────────────────────
// Main Media Metadata DTO
// ─────────────────────────────────────────────────────────────────────────────

export interface MediaMetadataDto {
  id: string;
  platform: string;
  title: string;
  author: string;
  authorUrl: string;
  duration: string;
  views: string;
  likes?: string;
  comments?: string;
  thumbnail: string;
  highResThumbnail?: string;
  type: 'video' | 'album' | 'audio' | 'playlist' | 'live';
  originalUrl: string;
  description?: string;
  tags?: string[];
  uploadDate?: string;
  subtitles?: SubtitleDto[];
  chapters?: ChapterDto[];
  streams?: StreamFormatDto[];
  images?: MediaImageDto[];
  playlistItems?: CrawlMediaItemDto[];

  /** True nếu đây là live stream đang phát */
  isLive?: boolean;

  /** URL HLS/DASH trực tiếp cho live stream */
  liveStreamUrl?: string;

  /** True nếu đây là video Reels (Instagram / Facebook) */
  isReel?: boolean;

  /** True nếu đây là video Shorts (YouTube) */
  isShort?: boolean;

  /** Tổng số item trong playlist/channel (nếu biết) */
  playlistCount?: number;
}

